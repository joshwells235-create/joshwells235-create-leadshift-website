// npm run placeholders
// Lists every open placeholder in the built site, page by page, and writes
// docs/placeholders.md. That file is generated: the hand-kept plan stays in
// docs/07-content-tracker.md, which this script never touches.
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const DIST = join(ROOT, 'dist');
const OUT = join(ROOT, 'docs', 'placeholders.md');

if (!existsSync(DIST)) {
  console.error('placeholders: no dist/ folder. Run `npm run build` first.');
  process.exit(1);
}

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const decode = (s) =>
  s.replace(/<[^>]+>/g, '').replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

const PH = /<span\b[^>]*\bdata-ph="([^"]*)"[^>]*>([\s\S]*?)<\/span>/g;

function scan(html) {
  const items = [];
  for (const m of html.matchAll(PH)) items.push({ text: decode(m[2]), note: decode(m[1]) });
  // Bracketed text that skipped the <Ph> component (should not happen).
  const rest = html
    .replace(/<script[\s\S]*?<\/script>/g, '')
    .replace(/<style[\s\S]*?<\/style>/g, '')
    .replace(PH, '')
    .replace(/<[^>]+>/g, ' ');
  const unmarked = [...decode(rest).matchAll(/\[[A-Z][^\]]{1,120}\]/g)].map((m) => m[0]);
  return { items, unmarked };
}

const pages = [];
let shared = null;
for (const file of walk(DIST).filter((f) => f.endsWith('.html')).sort()) {
  const html = readFileSync(file, 'utf8');
  const rel = relative(DIST, file).replace(/\.html$/, '');
  const url = rel === 'index' ? '/' : '/' + rel.replace(/\/index$/, '');
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/) || [, url])[1]);
  const footerAt = html.indexOf('<footer');
  const body = footerAt > -1 ? html.slice(0, footerAt) : html;
  const foot = footerAt > -1 ? html.slice(footerAt) : '';
  if (!shared && foot) shared = scan(foot);
  pages.push({ url, title, ...scan(body) });
}

const total = pages.reduce((n, p) => n + p.items.length, 0) + (shared ? shared.items.length : 0);
const date = new Date().toISOString().slice(0, 10);
let md = `# Placeholders in the preview (generated)\n\n`;
md += `Generated by \`npm run placeholders\` on ${date} from the built site. Do not edit by hand: change the page, then run it again. The plan for producing this content is \`docs/07-content-tracker.md\`.\n\n`;
md += `**${total} open placeholders** across ${pages.length} page(s), counting the shared footer once.\n`;
const table = (items) =>
  items.map((it, i) => `| ${i + 1} | ${it.text.replace(/\|/g, '\\|')} | ${(it.note || '').replace(/\|/g, '\\|')} |`).join('\n');
if (shared && shared.items.length) {
  md += `\n## Every page (footer)\n\n| # | Placeholder | What is missing |\n|---|---|---|\n${table(shared.items)}\n`;
}
for (const p of pages) {
  md += `\n## ${p.title} (\`${p.url}\`)\n\n`;
  md += p.items.length ? `| # | Placeholder | What is missing |\n|---|---|---|\n${table(p.items)}\n` : `No placeholders.\n`;
  if (p.unmarked.length) md += `\nBracketed text not using the placeholder component: ${p.unmarked.map((u) => '`' + u + '`').join(', ')}\n`;
}
writeFileSync(OUT, md);

console.log(`placeholders: ${total} open, written to docs/placeholders.md`);
if (shared) console.log(`  footer (every page): ${shared.items.length}`);
for (const p of pages) console.log(`  ${p.url}: ${p.items.length}${p.unmarked.length ? `  (+${p.unmarked.length} unmarked)` : ''}`);
